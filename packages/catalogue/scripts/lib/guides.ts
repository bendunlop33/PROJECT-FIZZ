import { existsSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { CatalogueEntrySchema, type CatalogueEntry } from '../../src/entry-schema.ts';
import { GuideSchema } from '../../src/figure/guide-schema.ts';
import { prepareGuide } from '../../src/figure/pose.ts';
import { fitCamera } from '../../src/figure/svg.ts';
import { EXERCISES_DIR, GUIDES_DIR, readJson } from './paths.ts';

export interface GuideFile {
  id: string;
  dir: string;
  path: string;
  raw: unknown;
  bytes: number;
  entry: CatalogueEntry | null;
}

/** Guide folders (`_rig`, `_templates` and other `_` folders are skipped). */
export function guideIds(): string[] {
  if (!existsSync(GUIDES_DIR)) return [];
  return readdirSync(GUIDES_DIR)
    .filter((d) => !d.startsWith('_') && !d.startsWith('.') && existsSync(join(GUIDES_DIR, d, 'guide.json')))
    .sort();
}

export function loadGuideFile(id: string): GuideFile {
  if (!/^[a-z0-9-]+$/.test(id)) throw new Error(`Not a guide id: ${id}`);
  const dir = join(GUIDES_DIR, id);
  const path = join(dir, 'guide.json');
  if (!existsSync(path)) throw new Error(`No guide at ${path}`);
  const read = readJson(path);
  if (!read.ok) throw new Error(`${path}: ${read.message}`);
  const entryPath = join(EXERCISES_DIR, `${id}.json`);
  let entry: CatalogueEntry | null = null;
  if (existsSync(entryPath)) {
    const e = readJson(entryPath);
    const parsed = e.ok ? CatalogueEntrySchema.safeParse(e.data) : null;
    entry = parsed?.success === true ? parsed.data : null;
  }
  return { id, dir, path, raw: read.data, bytes: statSync(path).size, entry };
}

/**
 * Source of `src/generated/guide-files.ts`: a static import of every
 * `guide.json` (so Metro bundles them, and nothing else from `guides/`: no
 * previews, no meta.json) plus each guide's fitted camera. Fitting samples a
 * whole cycle, which is slow on Hermes, so it is done here once; the app's
 * first frame then needs one pose. A guide that fails its schema gets
 * `camera: null` (`guide:check` reports the failure).
 */
export function guideIndexSource(ids: readonly string[]): string {
  const lines = [
    '// Generated by `npm run catalogue:index`. Do not edit; `catalogue:validate` fails when it is stale.',
    '// Static imports so Metro bundles every guide.json (never the previews). `camera` is',
    "// `fitCamera(prepareGuide(guide))` to 1e-6 H, precomputed so the app doesn't sample a whole cycle first.",
  ];
  ids.forEach((id, i) => lines.push(`import g${i} from '../../guides/${id}/guide.json';`));
  lines.push('');
  lines.push('export interface BundledGuideFile {');
  lines.push('  key: string;');
  lines.push('  raw: unknown;');
  lines.push('  camera: { cx: number; cy: number; size: number } | null;');
  lines.push('}');
  lines.push('');
  lines.push('export const BUNDLED_GUIDE_FILES: readonly BundledGuideFile[] = [');
  ids.forEach((id, i) => {
    const parsed = GuideSchema.safeParse(loadGuideFile(id).raw);
    const c = parsed.success ? fitCamera(prepareGuide(parsed.data)) : null;
    // Rounded to 1e-6 H (invisible at any size) so last-bit float differences between Node builds can't make the index look stale.
    const r6 = (n: number): string => String(Number(n.toFixed(6)) + 0);
    const camera = c === null ? 'null' : `{ cx: ${r6(c.cx)}, cy: ${r6(c.cy)}, size: ${r6(c.size)} }`;
    lines.push(`  { key: '${id}', raw: g${i}, camera: ${camera} },`);
  });
  lines.push('];');
  return `${lines.join('\n')}\n`;
}
