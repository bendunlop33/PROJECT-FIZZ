import { readdirSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const PACKAGE_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const EXERCISES_DIR = join(PACKAGE_ROOT, 'data', 'exercises');
export const GUIDES_DIR = join(PACKAGE_ROOT, 'guides');
export const INDEX_FILE = join(PACKAGE_ROOT, 'src', 'generated', 'exercise-files.ts');
export const GUIDE_INDEX_FILE = join(PACKAGE_ROOT, 'src', 'generated', 'guide-files.ts');

export function exerciseFileNames(): string[] {
  return readdirSync(EXERCISES_DIR)
    .filter((f) => f.endsWith('.json'))
    .sort();
}

export type JsonRead = { ok: true; data: unknown } | { ok: false; message: string };

export function readJson(path: string): JsonRead {
  try {
    return { ok: true, data: JSON.parse(readFileSync(path, 'utf8')) as unknown };
  } catch (error) {
    return { ok: false, message: error instanceof Error ? error.message : String(error) };
  }
}

/** Source of `src/generated/exercise-files.ts` for the given file names. */
export function indexSource(fileNames: readonly string[]): string {
  const lines = [
    '// Generated by `npm run catalogue:index`. Do not edit; `catalogue:validate` fails when it is stale.',
    '// Static imports so Metro bundles every entry (no network, no file reads at runtime).',
  ];
  fileNames.forEach((f, i) => lines.push(`import e${i} from '../../data/exercises/${f}';`));
  lines.push('');
  lines.push(`export const BUNDLED_EXERCISE_FILES: readonly unknown[] = [${fileNames.map((_, i) => `e${i}`).join(', ')}];`);
  return `${lines.join('\n')}\n`;
}
